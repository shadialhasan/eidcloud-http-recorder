<?php

declare(strict_types=1);

namespace EidCloud\HttpRecorder\Generators;

use EidCloud\HttpRecorder\Model\RecordedInteraction;

final class TestGenerator
{
    /**
     * @param RecordedInteraction[] $interactions
     */
    public function __construct(
        private readonly array $interactions
    ) {
    }

    /**
     * Generates a PHPUnit test class file content
     */
    public function generatePhpUnit(string $className = 'RecordedTrafficTest'): string
    {
        $code = "<?php\n\ndeclare(strict_types=1);\n\n";
        $code .= "use PHPUnit\\Framework\\TestCase;\n\n";
        $code .= "/**\n * Auto-generated by EidCloud HTTP Recorder\n */\n";
        $code .= "final class {$className} extends TestCase\n{\n";

        foreach ($this->interactions as $i => $interaction) {
            if ($interaction->method === 'CONNECT') {
                continue;
            }

            $testMethodName = 'test_' . strtolower($interaction->method) . '_' . preg_replace('/[^a-zA-Z0-9_]/', '_', trim(parse_url($interaction->uri, PHP_URL_PATH) ?? 'root', '/')) . '_' . ($i + 1);
            $testMethodName = trim($testMethodName, '_');

            $code .= "    public function {$testMethodName}(): void\n    {\n";
            $code .= "        \$expectedStatus = {$interaction->statusCode};\n";
            $code .= "        \$uri = '" . addslashes($interaction->uri) . "';\n";
            $code .= "        \$method = '{$interaction->method}';\n";
            $code .= "        \$requestBody = " . var_export($interaction->requestBody, true) . ";\n";
            $code .= "        \$requestHeaders = " . var_export($interaction->requestHeaders, true) . ";\n\n";
            $code .= "        // Mock or Replay Assertion\n";
            $code .= "        \$this->assertSame({$interaction->statusCode}, \$expectedStatus);\n";
            $code .= "        \$this->assertNotEmpty(\$uri);\n";

            if ($interaction->responseBody !== '') {
                $code .= "        \$expectedResponseBody = " . var_export($interaction->responseBody, true) . ";\n";
                $code .= "        \$this->assertNotEmpty(\$expectedResponseBody);\n";
            }

            $code .= "    }\n\n";
        }

        $code .= "}\n";
        return $code;
    }

    /**
     * Generates a Pest PHP test suite file content
     */
    public function generatePest(): string
    {
        $code = "<?php\n\ndeclare(strict_types=1);\n\n";
        $code .= "// Auto-generated Pest test suite by EidCloud HTTP Recorder\n\n";

        foreach ($this->interactions as $i => $interaction) {
            if ($interaction->method === 'CONNECT') {
                continue;
            }

            $path = parse_url($interaction->uri, PHP_URL_PATH) ?: '/';
            $description = "replays {$interaction->method} {$path} successfully with status {$interaction->statusCode} (#" . ($i + 1) . ")";

            $code .= "test('{$description}', function () {\n";
            $code .= "    \$expectedStatus = {$interaction->statusCode};\n";
            $code .= "    \$uri = '" . addslashes($interaction->uri) . "';\n";
            $code .= "    \$method = '{$interaction->method}';\n\n";
            $code .= "    expect(\$expectedStatus)->toBe({$interaction->statusCode});\n";
            $code .= "    expect(\$uri)->not->toBeEmpty();\n";
            $code .= "});\n\n";
        }

        return $code;
    }

    /**
     * Generates a standalone executable PHP cURL test script
     */
    public function generateExecutableCurlScript(): string
    {
        $code = "<?php\n\ndeclare(strict_types=1);\n\n";
        $code .= "/**\n * Standalone executable cURL test runner\n * Auto-generated by EidCloud HTTP Recorder\n */\n\n";
        $code .= "\$interactions = " . var_export(array_map(fn($it) => $it->toArray(), $this->interactions), true) . ";\n\n";
        $code .= "\$passed = 0;\n\$failed = 0;\n\n";
        $code .= "foreach (\$interactions as \$idx => \$item) {\n";
        $code .= "    if (\$item['method'] === 'CONNECT') continue;\n";
        $code .= "    echo sprintf(\"[%d/%d] Testing %s %s ... \", \$idx + 1, count(\$interactions), \$item['method'], \$item['uri']);\n";
        $code .= "    \$ch = curl_init();\n";
        $code .= "    curl_setopt(\$ch, CURLOPT_URL, \$item['uri']);\n";
        $code .= "    curl_setopt(\$ch, CURLOPT_CUSTOMREQUEST, \$item['method']);\n";
        $code .= "    curl_setopt(\$ch, CURLOPT_RETURNTRANSFER, true);\n";
        $code .= "    curl_setopt(\$ch, CURLOPT_SSL_VERIFYPEER, false);\n";
        $code .= "    curl_setopt(\$ch, CURLOPT_TIMEOUT, 15);\n";
        $code .= "    if (!empty(\$item['requestBody'])) {\n";
        $code .= "        curl_setopt(\$ch, CURLOPT_POSTFIELDS, \$item['requestBody']);\n";
        $code .= "    }\n";
        $code .= "    \$headers = [];\n";
        $code .= "    foreach (\$item['requestHeaders'] as \$k => \$v) {\n";
        $code .= "        if (in_array(strtolower(\$k), ['host', 'content-length', 'connection'])) continue;\n";
        $code .= "        \$headers[] = is_array(\$v) ? \"{\$k}: {\$v[0]}\" : \"{\$k}: {\$v}\";\n";
        $code .= "    }\n";
        $code .= "    if (!empty(\$headers)) {\n";
        $code .= "        curl_setopt(\$ch, CURLOPT_HTTPHEADER, \$headers);\n";
        $code .= "    }\n";
        $code .= "    \$response = curl_exec(\$ch);\n";
        $code .= "    \$statusCode = (int)curl_getinfo(\$ch, CURLINFO_HTTP_CODE);\n";
        $code .= "    curl_close(\$ch);\n\n";
        $code .= "    if (\$statusCode === (int)\$item['statusCode']) {\n";
        $code .= "        echo \"\\033[32mPASS\\033[0m (HTTP {\$statusCode})\\n\";\n";
        $code .= "        \$passed++;\n";
        $code .= "    } else {\n";
        $code .= "        echo sprintf(\"\\033[31mFAIL\\033[0m (Expected HTTP %d, got %d)\\n\", \$item['statusCode'], \$statusCode);\n";
        $code .= "        \$failed++;\n";
        $code .= "    }\n";
        $code .= "}\n\n";
        $code .= "echo PHP_EOL . \"Test Run Completed: {\$passed} passed, {\$failed} failed.\" . PHP_EOL;\n";
        $code .= "exit(\$failed > 0 ? 1 : 0);\n";

        return $code;
    }

    /**
     * Synthesizes reverse-engineered OpenAPI 3.1 specifications from live traffic
     *
     * @return array<string, mixed>
     */
    public function generateOpenApiSpec(string $title = 'Synthesized API Spec', string $version = '1.0.0'): array
    {
        $spec = [
            'openapi' => '3.1.0',
            'info' => [
                'title' => $title,
                'version' => $version,
                'description' => 'Reverse-engineered OpenAPI 3.1 specification synthesized by EidCloud HTTP Recorder',
            ],
            'paths' => [],
        ];

        foreach ($this->interactions as $interaction) {
            if ($interaction->method === 'CONNECT') {
                continue;
            }

            $parsedUri = parse_url($interaction->uri);
            $path = $parsedUri['path'] ?? '/';
            $method = strtolower($interaction->method);

            if (!isset($spec['paths'][$path])) {
                $spec['paths'][$path] = [];
            }

            $operation = [
                'summary' => strtoupper($method) . ' ' . $path,
                'responses' => [
                    (string)$interaction->statusCode => [
                        'description' => 'Recorded response with status ' . $interaction->statusCode,
                    ],
                ],
            ];

            // Response Schema
            if ($interaction->responseBody !== '') {
                $jsonDecoded = json_decode($interaction->responseBody, true);
                if (json_last_error() === JSON_ERROR_NONE && is_array($jsonDecoded)) {
                    $operation['responses'][(string)$interaction->statusCode]['content'] = [
                        'application/json' => [
                            'schema' => $this->inferJsonSchema($jsonDecoded),
                            'example' => $jsonDecoded,
                        ],
                    ];
                } else {
                    $operation['responses'][(string)$interaction->statusCode]['content'] = [
                        'text/plain' => [
                            'schema' => ['type' => 'string'],
                        ],
                    ];
                }
            }

            // Request Body Schema
            if ($interaction->requestBody !== '' && in_array(strtoupper($method), ['POST', 'PUT', 'PATCH'], true)) {
                $jsonDecoded = json_decode($interaction->requestBody, true);
                if (json_last_error() === JSON_ERROR_NONE && is_array($jsonDecoded)) {
                    $operation['requestBody'] = [
                        'required' => true,
                        'content' => [
                            'application/json' => [
                                'schema' => $this->inferJsonSchema($jsonDecoded),
                                'example' => $jsonDecoded,
                            ],
                        ],
                    ];
                }
            }

            $spec['paths'][$path][$method] = $operation;
        }

        return $spec;
    }

    /**
     * @param mixed $data
     * @return array<string, mixed>
     */
    private function inferJsonSchema(mixed $data): array
    {
        if (is_null($data)) {
            return ['type' => 'null'];
        }
        if (is_bool($data)) {
            return ['type' => 'boolean'];
        }
        if (is_int($data)) {
            return ['type' => 'integer'];
        }
        if (is_float($data)) {
            return ['type' => 'number'];
        }
        if (is_string($data)) {
            return ['type' => 'string'];
        }
        if (is_array($data)) {
            if (array_is_list($data)) {
                $firstElem = $data[0] ?? null;
                return [
                    'type' => 'array',
                    'items' => $firstElem !== null ? $this->inferJsonSchema($firstElem) : ['type' => 'string'],
                ];
            }

            $properties = [];
            foreach ($data as $key => $val) {
                $properties[(string)$key] = $this->inferJsonSchema($val);
            }
            return [
                'type' => 'object',
                'properties' => $properties,
            ];
        }

        return ['type' => 'string'];
    }
}
